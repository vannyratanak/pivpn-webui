def prune_old_logs(days: int):
    """Deletes vpn_events/traffic_flows/system_log_lines rows older than
    `days` — without this, traffic_flows and (especially) system_log_lines
    grow without bound (thousands of rows/day at this app's observed
    traffic rate, and system_log_lines covers the *entire* journal, not
    just VPN-relevant lines), unlike journald's own log rotation which did
    this for free under the old live-parsing design. Called once per
    ingest_logs.py run, not on any request path. (The dedicated daily
    prune_db.sh/systemd timer also covers this at a 30-day window — this
    per-run call and that one are redundant by design, not a conflict:
    whichever runs first wins, harmlessly.)"""
    conn = get_conn()
    try:
        cutoff = (datetime.now() - timedelta(days=days)).strftime("%Y-%m-%d %H:%M:%S")
        conn.execute("DELETE FROM vpn_events WHERE ts < %s", (cutoff,))
        conn.execute("DELETE FROM traffic_flows WHERE ts < %s", (cutoff,))
        conn.execute("DELETE FROM system_log_lines WHERE ts < %s", (cutoff,))
        conn.commit()
    finally:
        conn.close()
