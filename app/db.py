def _token_expiry() -> str:
    return (datetime.now() + timedelta(days=config.AGENT_TOKEN_TTL_DAYS)).strftime("%Y-%m-%d %H:%M:%S")


def create_server(name: str) -> tuple[int, str]:
    """Registers a new remote agent box and returns (id, raw_token) — the
    raw token is only ever available here, at creation time; only its
    hash is persisted (see servers.token_hash). Caller (manage_servers.py)
    is responsible for showing it to the operator exactly once, to paste
    into that box's agent .env as AGENT_TOKEN."""
    token = secrets.token_urlsafe(32)
    conn = get_conn()
    try:
        try:
            cur = conn.execute(
                "INSERT INTO servers (name, token_hash, token_expires_at) VALUES (%s, %s, %s) RETURNING id",
                (name, generate_password_hash(token), _token_expiry()),
            )
        except psycopg2.errors.UniqueViolation as exc:
            conn.rollback()
            raise ValueError(f"A server named '{name}' already exists.") from exc
        new_id = cur.fetchone()["id"]
        conn.commit()
        return new_id, token
    finally:
        conn.close()


def rotate_server_token(name: str) -> tuple[int, str] | None:
    """Issues a fresh token (and a fresh expiry) for an already-registered
    agent, without touching its id or name — the renewal path once
    AGENT_TOKEN_TTL_DAYS is approaching, or any time earlier if a token is
    suspected to have leaked. Returns None if no server has that name."""
    token = secrets.token_urlsafe(32)
    conn = get_conn()
    try:
        cur = conn.execute(
            "UPDATE servers SET token_hash=%s, token_expires_at=%s WHERE name=%s RETURNING id",
            (generate_password_hash(token), _token_expiry(), name),
        )
        row = cur.fetchone()
        if not row:
            return None
        conn.commit()
        return row["id"], token
    finally:
        conn.close()


def verify_server_token(server_id: int, token: str) -> str:
    """Returns 'ok', 'invalid' (wrong token or no such server_id), or
    'expired' — a string rather than bool so hub_gateway.py can audit-log
    *why* a hello was rejected, not just that it was."""
    conn = get_conn()
    try:
        row = conn.execute(
            "SELECT token_hash, token_expires_at FROM servers WHERE id=%s", (server_id,)
        ).fetchone()
        if not row or not check_password_hash(row["token_hash"], token):
            return "invalid"
        if row["token_expires_at"] and row["token_expires_at"] < datetime.now().strftime("%Y-%m-%d %H:%M:%S"):
            return "expired"
        return "ok"
    finally:
        conn.close()


