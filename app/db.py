"""Postgres wrapper for firewall rule storage (ported from sqlite3 — see
memory/project notes for the migration).

No ORM on purpose — same reasoning as before: a handful of tables, a
small dependency footprint. `?` placeholders became `%s` (psycopg2/
libpq convention); `AUTOINCREMENT` became `GENERATED BY DEFAULT AS IDENTITY`;
timestamp columns stayed TEXT (not TIMESTAMPTZ) storing the exact same
'YYYY-MM-DD HH:MM:SS' strings the rest of the app (vpnlog.py,
ingest_logs.py) already formats/compares as strings — switching to a
native timestamp type would have meant auditing every comparison site
across the codebase for a port that doesn't need it.

_PGConnection below exists because psycopg2, unlike sqlite3, has no
connection-level .execute() convenience — every call site in this file
(and in firewall.py, which receives a raw connection from
locked_transaction()) calls conn.execute(...) directly. This adds just
enough of that surface back so porting stayed a placeholder-syntax
change, not a structural rewrite of every call site.
"""
import contextlib
import secrets
from datetime import datetime, timedelta

import psycopg2
import psycopg2.errors
from psycopg2.extras import RealDictCursor
from werkzeug.security import check_password_hash, generate_password_hash

import config


class _PGConnection:
    def __init__(self, pg_conn):
        self._conn = pg_conn

    def execute(self, sql, params=None):
        cur = self._conn.cursor()
        cur.execute(sql, params if params is not None else ())
        return cur

    def executemany(self, sql, seq_of_params):
        cur = self._conn.cursor()
        cur.executemany(sql, seq_of_params)
        return cur

    def commit(self):
        self._conn.commit()

    def rollback(self):
        self._conn.rollback()

    def close(self):
        self._conn.close()

    def cursor(self):
        return self._conn.cursor()


def _connect():
    return psycopg2.connect(
        host=config.DB_HOST,
        port=config.DB_PORT,
        dbname=config.DB_NAME,
        user=config.DB_USER,
        password=config.DB_PASSWORD,
        cursor_factory=RealDictCursor,
    )


# Fixed, arbitrary key for the advisory lock below — any int64 works, this
# one has no special meaning beyond being unlikely to collide with some
# other, unrelated advisory lock this app might take out in the future.
_LOCKED_TRANSACTION_LOCK_KEY = 918273645


@contextlib.contextmanager
def locked_transaction():
    """Yields a connection for callers whose read-check-write sequence
    must be atomic against a *second concurrent caller doing the same
    kind of check* — e.g. "is this the last admin?", "would this rule
    change lock the admin out?". A plain get_conn()-per-call is fine for
    a single read or write, but a read-then-decide-then-write guard
    built from two separate calls has a real gap: two near-simultaneous
    requests can each read the same pre-write state before either
    commits, both pass their own check, and both proceed.

    First porting attempt used Postgres's row-level SELECT ... FOR UPDATE,
    matched to whatever rows each caller's specific check reads — real
    bug, caught live by this file's own concurrency regression tests:
    several call sites in firewall.py never got FOR UPDATE added (the
    dialect port that touched those files was a placeholder-syntax pass,
    not a locking-semantics audit), and set_client_block's "does a block
    row already exist" check has no row to lock *at all* when it doesn't
    exist yet — a race there can't be closed by locking rows that aren't
    there. Switched to a single pg_advisory_xact_lock instead: one fixed
    key, held for the whole transaction, released automatically on
    commit or rollback. Coarser than per-row locking, but this app's
    write volume (a handful of admins/moderators, not a public write-
    heavy API) makes that a non-issue, and it's a far more faithful port
    of what SQLite's BEGIN IMMEDIATE actually guaranteed here anyway — a
    single writer for the whole database, not per-row — while removing
    an entire class of "forgot to lock the right rows" bug outright.

    lock_timeout (5s, matching SQLite's own default busy_timeout) means
    a caller blocked behind someone else's still-open transaction fails
    with psycopg2.errors.LockNotAvailable instead of hanging forever —
    callers catch this the same way they used to catch
    sqlite3.OperationalError. (pg_advisory_xact_lock itself ignores
    lock_timeout unless its own statement_timeout-style setting applies
    — SET LOCAL lock_timeout does cover advisory locks specifically, per
    Postgres's own docs, so this still works as intended.)

    Commits on clean exit (including a plain `return` from inside the
    `with` block); rolls back and re-raises on any exception."""
    pg_conn = _connect()
    conn = _PGConnection(pg_conn)
    try:
        conn.execute("SET LOCAL lock_timeout = '5s'")
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (_LOCKED_TRANSACTION_LOCK_KEY,))
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


