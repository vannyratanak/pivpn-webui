def list_audit_page(
    q: str | None = None, page: int = 1, page_size: int = 50, since: str | None = None,
    actions: tuple[str, ...] | None = None,
) -> tuple[list[dict], int]:
    """Most recent first, server-side paginated and searched — backs the
    Logs page's Activity and User Auth tabs (Activity: actions=None, no
    restriction; User Auth: actions=AUTH_ACTIONS). Returns (rows,
    total_matching_count); see list_vpn_events_page's docstring for `q`
    and `since`'s exact contract (same conventions, same 'YYYY-MM-DD
    HH:MM:SS' cutoff format for `since`, since add_audit stores `ts` the
    same way)."""
    conn = get_conn()
    try:
        clauses = []
        params: list = []
        if actions:
            placeholders = ",".join("%s" for _ in actions)
            clauses.append(f"action IN ({placeholders})")
            params += list(actions)
        if q:
            like = f"%{_escape_like(q)}%"
            clauses.append(
                "(actor LIKE %s ESCAPE '\\' OR action LIKE %s ESCAPE '\\' OR target LIKE %s ESCAPE '\\' "
                "OR result LIKE %s ESCAPE '\\' OR detail LIKE %s ESCAPE '\\')"
            )
            params += [like, like, like, like, like]
        if since:
            clauses.append("ts >= %s")
            params.append(since)
        where_sql = ("WHERE " + " AND ".join(clauses)) if clauses else ""
        total = conn.execute(f"SELECT COUNT(*) AS count FROM audit_log {where_sql}", params).fetchone()["count"]
        rows = conn.execute(
            f"SELECT * FROM audit_log {where_sql} ORDER BY id DESC LIMIT %s OFFSET %s",
            [*params, page_size, (page - 1) * page_size],
        ).fetchall()
        return [dict(r) for r in rows], total
    finally:
        conn.close()


