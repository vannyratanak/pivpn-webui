# How long audit_log rows stick around before add_audit opportunistically
# prunes them — long enough to matter for a real incident review, short
# enough that the table doesn't grow forever from background noise. That
# noise is real, not hypothetical: the login page is now reachable from
# the public internet via the relay, and every failed attempt (including
# ones from bots that have no idea this is PiVPN, just scanning) writes
# a row here — see login_failures for the separate, shorter-lived table
# that actually drives rate-limiting.
AUDIT_LOG_RETENTION_DAYS = 90


def add_audit(actor: str, action: str, target: str = "", result: str = "ok", detail: str = ""):
    # Cutoff/insert timestamp both computed in Python (datetime.now(),
    # the box's actual local time, Asia/Phnom_Penh) rather than a SQL
    # date function — same reasoning as before: everything this column
    # is ever compared against elsewhere in the app is also a
    # Python-formatted string in this exact format, so there's one
    # single source of truth for "now" instead of the app and the
    # database needing to agree on a timezone.
    conn = get_conn()
    try:
        cutoff = (datetime.now() - timedelta(days=AUDIT_LOG_RETENTION_DAYS)).strftime("%Y-%m-%d %H:%M:%S")
        conn.execute("DELETE FROM audit_log WHERE ts < %s", (cutoff,))
        conn.execute(
            "INSERT INTO audit_log (ts, actor, action, target, result, detail) VALUES (%s,%s,%s,%s,%s,%s)",
            (datetime.now().strftime("%Y-%m-%d %H:%M:%S"), actor, action, target, result, (detail or "")[:500]),
        )
        conn.commit()
    finally:
        conn.close()


def list_audit(limit: int = 200) -> list[dict]:
    conn = get_conn()
    try:
        rows = conn.execute(
            "SELECT * FROM audit_log ORDER BY id DESC LIMIT %s", (limit,)
        ).fetchall()
        return [dict(r) for r in rows]
    finally:
        conn.close()


def record_login_failure(ip: str):
    """Also opportunistically prunes anything old enough that no lockout
    window could ever care about it again — no separate cleanup job
    needed for a table that only ever grows one row per failed attempt.
    Cutoff computed in Python (UTC, matching the original SQLite
    CURRENT_TIMESTAMP default's own UTC-ness) so it stays comparable
    against count_recent_login_failures' own Python-computed window —
    both sides need to agree on a clock, same reasoning as add_audit
    above, just UTC here instead of local time since that's what the
    stored ts values' own DEFAULT already produces."""
    from datetime import timezone

    conn = get_conn()
    try:
        cutoff = (datetime.now(timezone.utc) - timedelta(hours=1)).strftime("%Y-%m-%d %H:%M:%S")
        conn.execute("DELETE FROM login_failures WHERE ts < %s", (cutoff,))
        conn.execute("INSERT INTO login_failures (ip, ts) VALUES (%s, %s)",
                     (ip, datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")))
        conn.commit()
    finally:
        conn.close()


